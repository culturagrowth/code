/// Version of the control protocol spoken by this crate. Messages carrying any other version
/// are rejected by [`decode`] with [`ProtoError::UnsupportedVersion`].
pub const PROTOCOL_VERSION: u16 = 1;

/// Maximum size, in bytes, of one encoded message (envelope included).
pub const MAX_MESSAGE_BYTES: usize = 64 * 1024;
