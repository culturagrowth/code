//! duoclip-proto: the DuoClip peer-to-peer control protocol.
//!
//! Small JSON messages exchanged between DuoClip apps over the authenticated WebRTC data
//! channel (and, as a fallback, relayed by the Worker). Every message is strictly validated
//! on both the encode and the decode path, and nothing in this crate panics on untrusted
//! input: all failures surface as [`ProtoError`].
//!
//! # Conventions (shared by all DuoClip crates)
//!
//! - Time is `i64` nanoseconds.
//!   - `*_utc_ns`: UTC, POSIX nanoseconds (leap seconds not counted), from the app's global
//!     clock.
//!   - `*_local_ns`: the sender's own monotonic clock (QPC-derived on Windows). Only
//!     meaningful to the sender, except in the time ping/pong exchange.
//! - IDs are UUIDs (v4 when generated by the apps; the version is not enforced on receipt).
//!   On the wire only the canonical lowercase hyphenated form is accepted, the same one used in
//!   object keys and AADs, so an id has exactly one textual spelling.
//! - Intervals are half-open, `[from, to)`, and `from < to` must hold.
//! - Nanosecond timestamps exceed 2^53, so a JSON consumer written in JavaScript cannot read
//!   them losslessly; the Worker must treat these messages as opaque.
//!
//! # Wire format
//!
//! `encode` produces the JSON of an [`Envelope`] (`{"v":1,"msg":{"type":"...",...}}`);
//! `decode` enforces [`MAX_MESSAGE_BYTES`], parses, checks the version, and validates.
//!
//! # Example
//!
//! ```
//! use duoclip_proto::{decode, encode, ClipId, ClipRequest, DeviceId, Message};
//!
//! let req = ClipRequest::with_defaults(
//!     ClipId::new_random(),
//!     DeviceId::new_random(),
//!     1_700_000_000_000_000_000, // hotkey press, global UTC ns
//!     5_000_000,                 // current clock uncertainty, ns
//! );
//! let bytes = encode(&Message::ClipRequest(req.clone()))?;
//! assert_eq!(decode(&bytes)?, Message::ClipRequest(req));
//! # Ok::<(), duoclip_proto::ProtoError>(())
//! ```
//!
//! # Object keys
//!
//! [`object_key`], [`manifest_key`] and [`clip_prefix`] define the one canonical layout of
//! encrypted clip objects in the bucket. A received [`ChunkRef`] is only structurally checked
//! by `validate`; receivers must also call [`ChunkRef::verify_object_key`] with their own crew
//! id so the announced key really belongs to the announced clip, POV, quality and index.

